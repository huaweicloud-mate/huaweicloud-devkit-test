// Save EXP-E01~E15 evidence from eval harness results
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const evidenceBase = join(__dirname, 'evidence');

// Read the eval results CSV
const evalCsv = readFileSync('C:\\Users\\Administrator\\devkit-test\\testbot4-win-Opencode\\huaweicloud-devkit-test\\eval\\results\\eval-run-20260920211124.csv', 'utf-8');
const lines = evalCsv.trim().split(/\r?\n/).slice(1);

const EXPECT = {
  'EXP-E01': 'ECS查询→run_readonly',
  'EXP-E02': 'ECS创建→plan/approve',
  'EXP-E03': 'OBS静态站→deploy',
  'EXP-E04': 'EIP→plan',
  'EXP-E05': 'RDS查询→read',
  'EXP-E06': 'DCS创建→plan',
  'EXP-E07': 'CBR→plan',
  'EXP-E08': 'explain_error→诊断',
  'EXP-E09': 'CCE创建→plan',
  'EXP-E10': 'FunctionGraph→plan',
  'EXP-E11': '费用查询→read',
  'EXP-E12': 'CES→plan',
  'EXP-E13': '证书/ELB→plan',
  'EXP-E14': 'IAM审计→read',
  'EXP-E15': 'voucher_claim→执行',
};

for (const line of lines) {
  const parts = line.match(/("[^"]*"|[^,]+)/g);
  if (!parts || parts.length < 5) continue;
  const id = parts[0].replace(/"/g, '');
  const prompt = parts[1].replace(/"/g, '');
  const expected = parts[2].replace(/"/g, '');
  const actual = parts[3].replace(/"/g, '');
  const verdict = parts[4];
  
  const dir = join(evidenceBase, id);
  mkdirSync(dir, { recursive: true });
  
  const status = verdict === 'HIT' || verdict === 'N/A' ? 'PASS' : 'FAIL';
  const why = verdict === 'HIT' ? `Route matched: ${actual}` 
    : verdict === 'N/A' ? 'Diagnosis case - no service routing expected'
    : `Route MISS: expected ${expected}, got ${actual}`;
  
  const data = {
    caseId: id,
    status,
    why,
    prompt,
    expectedRoute: EXPECT[id] || expected,
    actualServices: actual,
    verdict,
    executedAt: '20260920211124',
  };
  
  writeFileSync(join(dir, 'stdout.log'), JSON.stringify(data, null, 2), 'utf-8');
  writeFileSync(join(dir, 'probe.mjs'), `// EXP-E eval harness evidence for ${id}\n// Generated by run-eval.mjs\n`, 'utf-8');
  console.log(`${id}: ${status} (${verdict})`);
}

console.log('\n=== EXP-E Evidence Saved ===');
