import { pathToFileURL } from 'node:url';
import { join } from 'node:path';
import { writeFileSync, mkdirSync } from 'node:fs';
const SRC = '/home/testbot2/devkit-test/testbot2-Linux-CodeArts CLI/hdk/plugins/huaweicloud-core/src';
const { callTool } = await import(pathToFileURL(join(SRC, 'tools.mjs')).href);
const proj = '/tmp/d3s3-proj'; mkdirSync(proj, { recursive: true });
writeFileSync(proj + '/index.html', '<!DOCTYPE html><html><body><h1>hdk-d3s3</h1></body></html>');
const conn = await callTool('huaweicloud_sandbox_connect', { source: 'CLI' });
const wsId = conn?.devStageId || conn?.sessionId;
console.log('connect:', conn?.status, 'ws=', (wsId||'').slice(0,10));
const up = await callTool('huaweicloud_sandbox_upload_project', { local_dir: proj, workspace_id: wsId });
console.log('upload_project ok:', up?.ok, 'md5Verified:', up?.md5Verified);
const dn = await callTool('huaweicloud_sandbox_deploy_nginx', { nginx_type: 'static', port: 8080, project: 'd3s3-proj', output_dir: '.', workspace_id: wsId });
console.log('deploy_nginx:', JSON.stringify(dn).slice(0,300));
const dc = await callTool('huaweicloud_sandbox_deploy_check', { port: 8080, project: 'd3s3-proj', output_dir: '.', workspace_id: wsId });
console.log('deploy_check 完整:', JSON.stringify(dc).slice(0,700));
const cs = await callTool('huaweicloud_sandbox_close_session', { workspace_id: wsId });
console.log('close_session ok:', !cs.__error);
console.log('===D3-S3 DONE===');
